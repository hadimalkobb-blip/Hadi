verses = {}
def v(s, a):
    """a whole verse, recorded for the page; its audio must exist"""
    k = f'{s}:{a}'
    verses[k] = T[(s, a)]
    assert os.path.exists(os.path.join(AYAT, f'{s:03d}{a:03d}.mp3')), f'no audio for {k}'
    return [s, a]
def ref(s, a):
    return f'{SURA_NAME[s]} {str(a).translate(str.maketrans("0123456789", "٠١٢٣٤٥٦٧٨٩"))}'

