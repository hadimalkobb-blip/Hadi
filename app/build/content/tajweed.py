import unicodedata
def norm(t):
    """sort the combining marks inside each letter cluster, so «لَّ» matches whatever order the text stores"""
    out, cl = [], []
    for ch in t:
        if unicodedata.combining(ch) or ch in '\u0670\u0653\u0654':
            cl.append(ch)
        else:
            out.extend(sorted(cl)); cl = []; out.append(ch)
    out.extend(sorted(cl))
    return ''.join(out)


def resolve(n, w, mark, nth=0):
    word = V[n][w]
    if isinstance(mark, tuple):
        _, code, *k = mark
        k = k[0] if k else 0
        spans = [s for s in TJ.get(f'{n}:{w}', []) if s[2] == code]
        assert spans, (n, w, mark)
        a, b, _ = spans[k]
        return a, b
    i = -1
    nw, nm = norm(word), norm(mark)
    for _ in range(nth + 1):
        i = nw.find(nm, i + 1)
        assert i >= 0, f'{mark!r} not in {word!r} ({n}:{w})'
    return i, i + len(mark)


